// Regenerates data.js from TileLord's per-expansion tile specs (shared/tiles/*.json).
// Usage: node tools/build-data.mjs <path-to-TileLord>/shared/tiles
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node tools/build-data.mjs <shared/tiles dir>");

const tiles = {};
const decks = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const spec = JSON.parse(readFileSync(join(dir, file), "utf8"));
  for (const t of spec.tiles) {
    const overlays = (t.overlays || []).map((o) => [o.image, o.pos[0], o.pos[1], o.scale ?? 1]);
    tiles[t.id] = overlays.length ? [t.image, overlays] : [t.image];
  }
  Object.assign(decks, spec.decks);
}

const out = `// Generated by tools/build-data.mjs — do not edit.
globalThis.TLTC_DATA = ${JSON.stringify({ tiles, decks })};
`;
writeFileSync(new URL("../data.js", import.meta.url), out);
console.log(`data.js: ${Object.keys(tiles).length} tiles, decks: ${Object.keys(decks).join(", ")}`);
